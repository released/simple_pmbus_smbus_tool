[CmdletBinding()]
param([string]$Version='', [string]$VersionFile='', [string]$RcFile='',
      [string]$VersionHeader='', [string]$VersionMacro='',
      [Parameter(Mandatory=$true)][string]$OutputHeader, [string]$Stamp='')
$ErrorActionPreference='Stop'
$sources=@(@($Version,$VersionFile,$RcFile,$VersionHeader) | Where-Object { $_ }).Count
if ($sources -ne 1) { throw 'Select exactly one existing version source.' }
if ($VersionFile) { $Version=[IO.File]::ReadAllText([IO.Path]::GetFullPath($VersionFile)).Trim() }
if ($RcFile) {
    $text=[IO.File]::ReadAllText([IO.Path]::GetFullPath($RcFile))
    $match=[regex]::Match($text,'(?m)^\s*FILEVERSION\s+(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*$')
    if (!$match.Success) { throw 'Numeric FILEVERSION source was not found.' }
    $Version='{0}.{1}.{2}.{3:D3}' -f [int]$match.Groups[1].Value,[int]$match.Groups[2].Value,[int]$match.Groups[3].Value,[int]$match.Groups[4].Value
}
if ($VersionHeader) {
    if ($VersionMacro -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { throw 'An explicit version macro is required.' }
    $text=[IO.File]::ReadAllText([IO.Path]::GetFullPath($VersionHeader))
    $pattern='(?m)^\s*#define\s+'+[regex]::Escape($VersionMacro)+'\s+L?"([0-9]+\.[0-9]+\.[0-9]+\.[0-9]+)"\s*$'
    $match=[regex]::Match($text,$pattern)
    if (!$match.Success) { throw 'The specified literal version macro was not found.' }
    $Version=$match.Groups[1].Value
}
if ($Version -notmatch '^([0-9])\.([0-9])\.([0-9])\.([0-9]{3})$' -or [int]$Matches[4] -lt 1) {
    throw 'Expected a.b.c.ddd, single-digit components and revision 001..999.'
}
$numeric=(@(1,2,3,4) | ForEach-Object { [int]$Matches[$_] }) -join ','
$moment=if ($Stamp) {
    [DateTimeOffset]::ParseExact($Stamp,'yyyy-MM-ddTHH:mm:sszzz',[Globalization.CultureInfo]::InvariantCulture,[Globalization.DateTimeStyles]::None)
} else { [DateTimeOffset]::Now }
$iso=$moment.ToString('yyyy-MM-ddTHH:mm:sszzz',[Globalization.CultureInfo]::InvariantCulture)
$display=$moment.ToString('yyyy-MM-dd HH:mm:ss',[Globalization.CultureInfo]::InvariantCulture)
$path=[IO.Path]::GetFullPath($OutputHeader)
if ([IO.Path]::GetFileName($path) -cne 'tool_build_identity.h') { throw 'Output must be the dedicated tool_build_identity.h header.' }
$parent=[IO.Path]::GetDirectoryName($path)
for ($cursor=$path; $cursor; $cursor=[IO.Path]::GetDirectoryName($cursor)) {
    if ((Test-Path -LiteralPath $cursor) -and ((Get-Item -LiteralPath $cursor -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'Build identity output cannot traverse a reparse point.' }
}
[void][IO.Directory]::CreateDirectory($parent)
$body=@"
#pragma once
// Generated by the build; the existing product version source remains authoritative.
#define TOOL_BUILD_VERSION_TEXT "$Version"
#define TOOL_BUILD_VERSION_W L"$Version"
#define TOOL_BUILD_VERSION_NUMERIC $numeric
#define TOOL_BUILD_TIMESTAMP_ISO "$iso"
#define TOOL_BUILD_TIMESTAMP_ISO_W L"$iso"
#define TOOL_BUILD_DISPLAY_TIME_W L"$display"
"@
$temporary=Join-Path $parent ('.tool-build-'+[guid]::NewGuid().ToString('N')+'.tmp')
try {
    [IO.File]::WriteAllText($temporary,$body+[Environment]::NewLine,(New-Object Text.UTF8Encoding($false)))
    if (Test-Path -LiteralPath $path) { [IO.File]::Replace($temporary,$path,[NullString]::Value) }
    else { [IO.File]::Move($temporary,$path) }
} finally {
    if (Test-Path -LiteralPath $temporary -PathType Leaf) { Remove-Item -LiteralPath $temporary -ErrorAction Stop }
}
Write-Output ('Prepared v'+$Version+' | BUILD '+$display)
